function rect(west, south, east, north) {
  return {
    type: 'Polygon',
    coordinates: [[
      [west, south],
      [east, south],
      [east, north],
      [west, north],
      [west, south],
    ]],
  }
}

function poly(rings) {
  return { type: 'Polygon', coordinates: rings }
}

function feature(polityId, color, name, geometry, note) {
  return {
    type: 'Feature',
    properties: { polityId, color, name, ...(note ? { note } : {}) },
    geometry,
  }
}

